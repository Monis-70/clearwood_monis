import type { SeedProduct, SeedProductSpec, SeedProductVariant } from './demoProducts';

/**
 * The bulk of the demo catalog.
 *
 * `demoProducts.ts` holds the fourteen hand-written showcase pieces; these fill the shelves so
 * facets, price histograms, sorting and pagination have something real to work against. Everything
 * here is deterministic — same order, same SKUs, same stock every run — so re-seeding never moves
 * a row count.
 */

const IN_HOUSE = 'Built start-to-finish in our own workshop — frame, upholstery and finish.';

interface ExtraProductInput {
  sku: string;
  slug: string;
  name: string;
  subtitle: string;
  summary: string;
  categories: string[];
  basePricePaise: number;
  compareAtPricePaise?: number;
  variantAttributes: string[];
  /** Each entry is the attribute-code -> value-code map for one variant. */
  combos: Record<string, string>[];
  /** Opening stock per variant, in the same order as `combos`. 0 means out of stock. */
  stock: number[];
  specs?: SeedProductSpec[];
  variantUplift?: number[];
  soldCount?: number;
  /** Basis points of a five-star scale: 10000 = one star, so 4.4 stars is 44000. */
  ratingAvgBp?: number;
  ratingCount?: number;
  isFeatured?: boolean;
  isNewArrival?: boolean;
  isBestSeller?: boolean;
  isSpecialCollection?: boolean;
  isMadeToOrder?: boolean;
  allowCustomization?: boolean;
  leadTimeDays?: number;
  warrantyMonths?: number;
  weightGrams?: number;
  lengthMm?: number;
  widthMm?: number;
  heightMm?: number;
}

function suffixFor(combo: Record<string, string>): string {
  return Object.values(combo)
    .map((value) =>
      value
        .replace(/[^a-z0-9]/gi, '')
        .slice(0, 3)
        .toUpperCase(),
    )
    .join('-');
}

function build(input: ExtraProductInput): SeedProduct {
  const variants: SeedProductVariant[] = input.combos.map((combo, index) => ({
    suffix: suffixFor(combo),
    attributes: combo,
    isDefault: index === 0,
    stockQty: input.stock[index] ?? 0,
    ...(input.variantUplift?.[index]
      ? { pricePaise: input.basePricePaise + input.variantUplift[index]! }
      : {}),
  }));

  return {
    sku: input.sku,
    slug: input.slug,
    name: input.name,
    subtitle: input.subtitle,
    shortDescription: input.summary,
    description: `${input.summary} ${IN_HOUSE}`,
    productType: 'VARIABLE',
    basePricePaise: input.basePricePaise,
    ...(input.compareAtPricePaise === undefined
      ? {}
      : { compareAtPricePaise: input.compareAtPricePaise }),
    taxClassCode: 'GST_18',
    categories: input.categories,
    specs: input.specs ?? [
      { attribute: 'WOOD_TYPE', value: 'sheesham' },
      { attribute: 'ASSEMBLY_TYPE', value: 'pre_assembled' },
      { attribute: 'WARRANTY', value: '2_years' },
    ],
    variantAttributes: input.variantAttributes,
    variants,
    warrantyMonths: input.warrantyMonths ?? 24,
    ...(input.leadTimeDays === undefined ? {} : { leadTimeDays: input.leadTimeDays }),
    ...(input.isMadeToOrder === undefined ? {} : { isMadeToOrder: input.isMadeToOrder }),
    ...(input.allowCustomization === undefined
      ? {}
      : { allowCustomization: input.allowCustomization }),
    assemblyRequired: false,
    manufacturingNote: IN_HOUSE,
    careInstructions: 'Dust weekly with a dry cloth; keep out of direct sunlight.',
    ...(input.isFeatured === undefined ? {} : { isFeatured: input.isFeatured }),
    ...(input.isNewArrival === undefined ? {} : { isNewArrival: input.isNewArrival }),
    ...(input.isSpecialCollection === undefined
      ? {}
      : { isSpecialCollection: input.isSpecialCollection }),
    ...(input.isBestSeller === undefined ? {} : { isBestSeller: input.isBestSeller }),
    soldCount: input.soldCount ?? 0,
    ratingAvgBp: input.ratingAvgBp ?? 0,
    ratingCount: input.ratingCount ?? 0,
    ...(input.lengthMm === undefined ? {} : { lengthMm: input.lengthMm }),
    ...(input.widthMm === undefined ? {} : { widthMm: input.widthMm }),
    ...(input.heightMm === undefined ? {} : { heightMm: input.heightMm }),
    weightGrams: input.weightGrams ?? 25_000,
  };
}

